// @ts-check
'use strict';

const fs = require('node:fs');
const path = require('node:path');

/**
 * @typedef {{
 *   file: string,
 *   content: string,
 *   variables: string[],
 * }} PipelineTemplate
 *   file: path relative to the repo root; variables: CI secrets/variables the
 *   user must add by hand (the tool never sets them).
 */

const NPM_INSTALL = 'npm install -g @openwt-vn/owlet-lens';

// The same exit-code handling the shipped GitLab and Bitbucket templates use:
// 0 and 1 mean "ran fine", everything else fails the job.
const RUN_BLOCK_LINES = (provider) => [
  'fail=0',
  'for cmd in reply review; do',
  '  set +e',
  `  owlet-lens "$cmd" --provider=${provider}`,
  '  code=$?',
  '  set -e',
  '  if [ "$code" -eq 0 ] || [ "$code" -eq 1 ]; then',
  '    echo "owlet-lens $cmd completed (exit $code)"',
  '  else',
  '    echo "owlet-lens $cmd failed or gated (exit $code)"',
  '    fail="$code"',
  '  fi',
  'done',
  'exit "$fail"',
];

/** @param {string[]} lines @param {number} spaces */
function indent(lines, spaces) {
  const pad = ' '.repeat(spaces);
  return lines.map((l) => (l === '' ? '' : pad + l)).join('\n');
}

/**
 * @param {string} keyEnv name of the LLM key variable, e.g. ANTHROPIC_API_KEY
 * @returns {PipelineTemplate}
 */
function githubTemplate(keyEnv) {
  const content = `# Generated by \`owlet-lens init\`.
# Reviews every pull request and reads developer replies in review threads.
# Add the secret ${keyEnv} under Settings > Secrets and variables > Actions.
# Docs: https://github.com/openwt-vn/owlet-lens/blob/main/docs/github-action.md
name: AI Code Review

on:
  pull_request:
    types: [opened, synchronize, reopened]
  pull_request_review_comment:
    types: [created]

jobs:
  ai-review:
    permissions:
      contents: read
      pull-requests: write
    uses: openwt-vn/owlet-lens/.github/workflows/ai-review-reusable.yml@v1
    secrets: inherit
    with:
      # Required. Use '["self-hosted"]' to run on your own runners.
      runner: '["ubuntu-latest"]'
`;
  return { file: '.github/workflows/ai-review.yml', content, variables: [keyEnv] };
}

/**
 * @param {string} keyEnv
 * @returns {PipelineTemplate}
 */
function gitlabTemplate(keyEnv) {
  const run = indent(RUN_BLOCK_LINES('gitlab'), 6);
  const content = `# Generated by \`owlet-lens init\`.
# Reviews merge requests. \`reply\` runs first so the review sees the latest
# developer answers.
# Add these CI/CD variables (Settings > CI/CD > Variables):
#   ${keyEnv}  the key of your LLM provider
#   GITLAB_TOKEN  a project or group access token with the \`api\` scope
# Docs: https://github.com/openwt-vn/owlet-lens/blob/main/docs/gitlab-setup.md
owlet-lens-review:
  image: node:20-alpine
  rules:
    - if: $CI_PIPELINE_SOURCE == "merge_request_event"
  script:
    - ${NPM_INSTALL}
    - |
${run}
`;
  return { file: '.gitlab-ci.yml', content, variables: [keyEnv, 'GITLAB_TOKEN'] };
}

/**
 * @param {string} keyEnv
 * @returns {PipelineTemplate}
 */
function bitbucketTemplate(keyEnv) {
  const run = indent(RUN_BLOCK_LINES('bitbucket'), 14);
  const content = `# Generated by \`owlet-lens init\`.
# Reviews pull requests. \`reply\` runs first so the review sees the latest
# developer answers (Bitbucket has no comment trigger, so replies are read on
# the next push).
# Add these secured repository variables (Repository settings > Repository variables):
#   ${keyEnv}  the key of your LLM provider
#   AI_REVIEW_TOKEN  an access token with the \`pullrequest:write\` scope
# Docs: https://github.com/openwt-vn/owlet-lens#other-platforms
image: node:20

pipelines:
  pull-requests:
    '**':
      - step:
          name: AI code review
          script:
            - ${NPM_INSTALL}
            - |
${run}
`;
  return { file: 'bitbucket-pipelines.yml', content, variables: [keyEnv, 'AI_REVIEW_TOKEN'] };
}

/**
 * Template for a review provider, or null when none exists (Azure DevOps).
 * @param {string} provider
 * @param {string} keyEnv
 * @returns {PipelineTemplate | null}
 */
function pipelineTemplate(provider, keyEnv) {
  if (provider === 'github') return githubTemplate(keyEnv);
  if (provider === 'gitlab') return gitlabTemplate(keyEnv);
  if (provider === 'bitbucket') return bitbucketTemplate(keyEnv);
  return null;
}

/**
 * Write the template under cwd. An existing file is never touched: the template
 * goes next to it with a `.owlet-lens` suffix so the user can merge by hand.
 * @param {string} cwd
 * @param {PipelineTemplate} tpl
 * @returns {{ path: string, merged: boolean }} path relative to cwd; merged is
 *   true when the template went to a side file because the target existed
 */
function writePipeline(cwd, tpl) {
  const target = path.join(cwd, tpl.file);
  const exists = fs.existsSync(target);
  const rel = exists ? `${tpl.file}.owlet-lens` : tpl.file;
  const dest = path.join(cwd, rel);
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  fs.writeFileSync(dest, tpl.content, 'utf8');
  return { path: rel, merged: exists };
}

module.exports = { pipelineTemplate, writePipeline };
